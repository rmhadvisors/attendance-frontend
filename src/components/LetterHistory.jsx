import { useCallback, useEffect, useState } from "react"
import { Icon } from "./FormParts"
import { inputClass } from "../constants/formStyles"
import { ICONS, LETTERS } from "../constants/letterTypes"
import { deleteLetterHistory, getLetterHistory } from "../services/letterService"
import { downloadFile } from "../utils/downloadPdf"
import { getApiErrorMessage } from "../api/axios"

const PAGE_SIZE = 50

function formatWhen(iso) {
  if (!iso) return "-"
  return new Date(iso).toLocaleString([], {
    day: "2-digit", month: "short", year: "numeric", hour: "numeric", minute: "2-digit",
  })
}

// Letters > History: every letter file that was generated, with re-download and delete.
export default function LetterHistory() {
  const [items, setItems] = useState([])
  const [total, setTotal] = useState(0)
  const [type, setType] = useState("")
  const [search, setSearch] = useState("")
  const [query, setQuery] = useState("")
  const [loading, setLoading] = useState(true)
  const [busyId, setBusyId] = useState(null)
  const [error, setError] = useState("")

  // Wait for the admin to stop typing before searching.
  useEffect(() => {
    const t = setTimeout(() => setQuery(search.trim()), 300)
    return () => clearTimeout(t)
  }, [search])

  const load = useCallback(async (offset = 0) => {
    setLoading(true)
    setError("")
    try {
      const params = { limit: PAGE_SIZE, offset }
      if (type) params.letter_type = type
      if (query) params.q = query
      const data = await getLetterHistory(params)
      setItems((prev) => (offset === 0 ? data.items : [...prev, ...data.items]))
      setTotal(data.total)
    } catch (err) {
      setError(getApiErrorMessage(err, "Could not load letter history."))
    } finally {
      setLoading(false)
    }
  }, [type, query])

  useEffect(() => { load(0) }, [load])

  const handleDownload = async (item) => {
    setBusyId(item.id)
    setError("")
    try {
      await downloadFile(`/letters/history/${item.id}/download`, item.filename || `${item.letter_label}.docx`)
    } catch (err) {
      setError(getApiErrorMessage(err, "Could not download this letter."))
    } finally {
      setBusyId(null)
    }
  }

  const handleDelete = async (item) => {
    if (!window.confirm(`Delete the ${item.letter_label} for ${item.employee_name} from history? The saved file will be removed.`)) return
    setBusyId(item.id)
    setError("")
    try {
      await deleteLetterHistory(item.id)
      setItems((prev) => prev.filter((i) => i.id !== item.id))
      setTotal((n) => Math.max(0, n - 1))
    } catch (err) {
      setError(getApiErrorMessage(err, "Could not delete this letter."))
    } finally {
      setBusyId(null)
    }
  }

  return (
    <div className="space-y-4">
      <div className="flex flex-col gap-3 sm:flex-row">
        <input
          type="search" value={search} onChange={(e) => setSearch(e.target.value)}
          placeholder="Search by employee name" className={`${inputClass} sm:max-w-xs`}
        />
        <select value={type} onChange={(e) => setType(e.target.value)} className={`${inputClass} sm:max-w-xs`}>
          <option value="">All letters</option>
          {Object.entries(LETTERS).map(([key, l]) => <option key={key} value={key}>{l.label}</option>)}
        </select>
      </div>

      {error && (
        <p className="rounded-xl border border-red-200 bg-red-50 px-4 py-3 text-sm font-medium text-red-700">{error}</p>
      )}

      {loading && items.length === 0 ? (
        <div className="flex items-center justify-center gap-3 py-16 text-sm font-semibold text-gray-400">
          <div className="h-5 w-5 animate-spin rounded-full border-2 border-emerald-600 border-t-transparent" />
          Loading history…
        </div>
      ) : items.length === 0 ? (
        <div className="rounded-2xl border border-dashed border-gray-200 bg-white px-4 py-14 text-center text-sm text-gray-500">
          {query || type ? "No letters match your search." : "No letters generated yet."}
        </div>
      ) : (
        <div className="overflow-hidden rounded-2xl border border-gray-200 bg-white shadow-sm">
          <div className="overflow-x-auto">
            <table className="min-w-full text-left text-sm">
              <thead className="border-b border-gray-100 bg-gray-50 text-[11px] font-bold uppercase tracking-wider text-gray-500">
                <tr>
                  <th className="px-4 py-3">Date</th>
                  <th className="px-4 py-3">Letter</th>
                  <th className="px-4 py-3">Employee</th>
                  <th className="px-4 py-3">Generated by</th>
                  <th className="px-4 py-3 text-right">Actions</th>
                </tr>
              </thead>
              <tbody className="divide-y divide-gray-100">
                {items.map((item) => (
                  <tr key={item.id} className="hover:bg-gray-50/60">
                    <td className="whitespace-nowrap px-4 py-3 text-gray-600">{formatWhen(item.created_at)}</td>
                    <td className="px-4 py-3 font-semibold text-gray-900">{item.letter_label}</td>
                    <td className="px-4 py-3 text-gray-700">{item.employee_name}</td>
                    <td className="px-4 py-3 text-gray-500">{item.generated_by_name || "-"}</td>
                    <td className="whitespace-nowrap px-4 py-3 text-right">
                      <button
                        type="button" onClick={() => handleDownload(item)}
                        disabled={!item.downloadable || busyId === item.id}
                        title={item.downloadable ? "Download" : "The file was not saved for this letter"}
                        className="inline-flex items-center gap-1.5 rounded-lg px-3 py-1.5 text-xs font-bold text-emerald-700 transition hover:bg-emerald-50 disabled:cursor-not-allowed disabled:text-gray-300 disabled:hover:bg-transparent"
                      >
                        <Icon path={ICONS.download} className="h-4 w-4" />
                        Download
                      </button>
                      <button
                        type="button" onClick={() => handleDelete(item)} disabled={busyId === item.id}
                        className="ml-1 rounded-lg px-3 py-1.5 text-xs font-bold text-red-600 transition hover:bg-red-50 disabled:text-gray-300"
                      >
                        Delete
                      </button>
                    </td>
                  </tr>
                ))}
              </tbody>
            </table>
          </div>
          <div className="flex items-center justify-between border-t border-gray-100 px-4 py-3 text-xs text-gray-500">
            <span>Showing {items.length} of {total}</span>
            {items.length < total && (
              <button
                type="button" onClick={() => load(items.length)} disabled={loading}
                className="rounded-lg border border-gray-300 bg-white px-3 py-1.5 font-semibold text-gray-700 transition hover:bg-gray-50 disabled:opacity-60"
              >
                {loading ? "Loading…" : "Load more"}
              </button>
            )}
          </div>
        </div>
      )}
    </div>
  )
}
